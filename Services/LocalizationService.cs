    public static string GetSystemLanguageCode()
    {
        try
        {
            var ci = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant();
            if (Languages.Any(l => l.Code == ci))
                return ci;
        }
        catch { }
        return "ru";
    }

    public static LanguageDefinition GetLanguage(string codeOrDisplay)
    {
        return Languages.FirstOrDefault(l =>
            l.DisplayName.Equals(codeOrDisplay, StringComparison.OrdinalIgnoreCase) ||
            l.Code.Equals(codeOrDisplay, StringComparison.OrdinalIgnoreCase) ||
            codeOrDisplay.Contains($"({l.Code})", StringComparison.OrdinalIgnoreCase))
            ?? Languages[0];
    }

